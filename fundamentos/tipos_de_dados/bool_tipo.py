"""
BOOL

bool -> Booleano

Existem duas respostas possíveis:
True  -> Verdadeiro
False -> Falso
"""

print(10 == 10)  # True
print(10 == 11)  # False

print(type(True))    # <class 'bool'>
print(type(False))   # <class 'bool'>

print(type(10 == 10))   # <class 'bool'>
print(type(10 == 11))   # <class 'bool'>