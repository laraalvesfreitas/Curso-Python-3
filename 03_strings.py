"""
STRINGS

str -> string -> texto

Strings são textos que estão dentro de aspas.
"""


# ==================================================
# ASPAS SIMPLES
# ==================================================

print('Luiz Otávio')

print(1, 'Luiz "Otávio"')


# ==================================================
# ASPAS DUPLAS
# ==================================================

print("Luiz Otávio")

print(2, "Luiz 'Otávio'")


# ==================================================
# ESCAPE
# ==================================================

print("Luiz \"Otávio\"")


# ==================================================
# R
# ==================================================

print(r"Luiz \"Otávio\"")