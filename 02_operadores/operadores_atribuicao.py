"""
Operadores de atribuição → usados para atribuir
ou atualizar o valor de uma variável.

=   → atribui um valor
+=  → adiciona um valor
-=  → subtrai um valor
*=  → multiplica por um valor
/=  → divide por um valor
//= → realiza divisão inteira
**= → realiza exponenciação
%=  → atribui o resto da divisão
"""

contador = 10

