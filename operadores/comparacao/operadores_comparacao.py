"""
OPERADORES DE COMPARAÇÃO (RELACIONAIS)

>  → maior
>= → maior ou igual
<  → menor
<= → menor ou igual
== → igual
!= → diferente

Os operadores de comparação sempre retornam:
True → verdadeiro
False → falso
"""

maior = 2 > 1
maior_ou_igual = 2 >= 2
menor = 1 < 2
menor_ou_igual = 2 <= 2
igual = 'a' == 'a'
diferente = 'a' != 'b'

print(maior)            # True
print(maior_ou_igual)   # True
print(menor)            # True
print(menor_ou_igual)   # True
print(igual)            # True
print(diferente)        # True