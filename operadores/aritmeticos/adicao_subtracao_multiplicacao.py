"""
ADIÇÃO, SUBTRAÇÃO E MULTIPLICAÇÃO

+ → soma dois valores.
- → subtrai um valor de outro.
* → multiplica dois valores.
"""

adicao = 10 + 10
subtracao = 10 - 5
multiplicacao = 10 * 10

print('Adição', adicao)              # 20
print('Subtração', subtracao)        # 5
print('Multiplicação', multiplicacao)  # 100